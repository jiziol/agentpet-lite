import Foundation

/// Recognizes direct invocations, never shell snippets or mentions in text.
enum HookCommandOwnership {
    static func owns(_ command: String) -> Bool {
        guard let args = words(command), args.count == 2 || args.count == 4,
              args[1] == "hook", (args[0] as NSString).lastPathComponent == "agentpet",
              args[0] == "agentpet" || args[0].hasPrefix("/") else { return false }
        return args.count == 2 || (args[2] == "--agent" && AgentKind(rawValue: args[3]) != nil)
    }

    /// A retired file may also contain an explicitly maintained AgentPet command.
    /// Keep that user choice; only this source or the old untagged command retires.
    static func owns(_ command: String, retiredKind: AgentKind) -> Bool {
        guard owns(command), let args = words(command) else { return false }
        return args.count == 2 || AgentKind(rawValue: args[3]) == retiredKind
    }

    // Deliberately a small literal shell grammar. Unsupported syntax is foreign.
    static func words(_ text: String) -> [String]? {
        var result: [String] = [], word = ""
        var quote: Character?, escaped = false, started = false
        for c in text {
            if c == "\n" || c == "\r" || c == "\0" { return nil }
            if escaped { word.append(c); escaped = false; started = true; continue }
            if c == "\\" && quote != "'" { escaped = true; continue }
            if let q = quote {
                if c == q { quote = nil }
                else {
                    if q == "\"" && (c == "$" || c == "`") { return nil }
                    word.append(c)
                }
                continue
            }
            if c == "'" || c == "\"" { quote = c; started = true }
            else if c == " " || c == "\t" {
                if started { result.append(word); word = ""; started = false }
            } else {
                if ";|&<>$`(){}[]*?!#~".contains(c) { return nil }
                word.append(c); started = true
            }
        }
        guard quote == nil, !escaped else { return nil }
        if started { result.append(word) }
        return result
    }

    /// Only scalar literal/basic TOML strings generated by this installer.
    /// Arrays, multiline values and unknown escape forms are preserved.
    static func ownsTOMLAssignment(_ line: String, retiredKind: AgentKind? = nil) -> Bool {
        guard let equals = line.firstIndex(of: "=") else { return false }
        let value = line[line.index(after: equals)...].trimmingCharacters(in: .whitespaces)
        guard let quote = value.first, quote == "'" || quote == "\"" else { return false }
        var escaped = false
        for i in value.indices.dropFirst() {
            let c = value[i]
            if escaped { escaped = false; continue }
            if quote == "\"" && c == "\\" { escaped = true; continue }
            if c == quote {
                let tail = value[value.index(after: i)...].trimmingCharacters(in: .whitespaces)
                guard tail.isEmpty || tail.hasPrefix("#") else { return false }
                let command: String?
                if quote == "'" { command = String(value[value.index(after: value.startIndex)..<i]) }
                else { command = try? JSONDecoder().decode(String.self, from: Data(value[...i].utf8)) }
                return command.map { command in
                    retiredKind.map { owns(command, retiredKind: $0) } ?? owns(command)
                } ?? false
            }
        }
        return false
    }
}
