        self.notificationVersion = session.notificationVersion
        self.readThroughVersion = session.readThroughVersion
        self.turnStartedAt = session.turnStartedAt
        self.turnEndedAt = session.turnEndedAt
        self.codexTurnID = session.codexTurnID
        self.codexLifecycleAt = session.codexLifecycleAt
        self.codexTurnResult = session.codexTurnResult
        self.antigravityTurnResult = session.antigravityTurnResult
